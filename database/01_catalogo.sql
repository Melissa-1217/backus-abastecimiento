CREATE TABLE producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    marca VARCHAR(80) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE presentacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL REFERENCES producto(id),
    descripcion VARCHAR(120) NOT NULL,
    contenido_ml INTEGER NOT NULL CHECK (contenido_ml > 0),
    unidades_por_paquete INTEGER NOT NULL
        CHECK (unidades_por_paquete > 0),
    precio NUMERIC(10, 2) NOT NULL CHECK (precio >= 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presentacion_id BIGINT NOT NULL REFERENCES presentacion(id),
    zona VARCHAR(100) NOT NULL,
    cantidad INTEGER NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
    UNIQUE (presentacion_id, zona)
);
