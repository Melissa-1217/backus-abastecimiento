-- Galerías de productos y de sus presentaciones.
CREATE TABLE IF NOT EXISTS imagen_catalogo (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 producto_id BIGINT REFERENCES producto(id),
 presentacion_id BIGINT REFERENCES presentacion(id),
 url VARCHAR(1000) NOT NULL,
 orden INTEGER NOT NULL DEFAULT 0,
 CHECK ((producto_id IS NOT NULL AND presentacion_id IS NULL) OR (producto_id IS NULL AND presentacion_id IS NOT NULL))
);

-- Trazabilidad de los ajustes manuales de existencias.
CREATE TABLE IF NOT EXISTS ajuste_inventario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inventario_id BIGINT NOT NULL REFERENCES inventario(id),
 cantidad_anterior INTEGER NOT NULL CHECK(cantidad_anterior >= 0),
 cantidad_nueva INTEGER NOT NULL CHECK(cantidad_nueva >= 0),
 motivo VARCHAR(300) NOT NULL,
 administrador VARCHAR(254) NOT NULL,
 fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

